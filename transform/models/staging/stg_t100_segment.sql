-- Typed T-100 segments. Weights are pounds, distance statute miles, times minutes.
-- Service class: F scheduled passenger/cargo, G scheduled all-cargo, L non-scheduled passenger/cargo,
-- P non-scheduled all-cargo. Scheduled departures are only meaningful for F and G.
select
    cast(year as integer)                          as year,
    cast(month as integer)                         as month,
    make_date(cast(year as integer), cast(month as integer), 1) as month_start,
    unique_carrier                                 as carrier,
    unique_carrier_name                            as carrier_name,
    cast(carrier_group_new as integer)             as carrier_group,
    origin,
    origin_city_name,
    origin_state_abr                               as origin_state,
    origin_country,
    dest,
    dest_city_name,
    dest_state_abr                                 as dest_state,
    dest_country,
    cast(aircraft_group as integer)                as aircraft_group,
    cast(aircraft_type as integer)                 as aircraft_type,
    cast(aircraft_config as integer)               as aircraft_config,
    class                                          as service_class,
    class in ('F', 'G')                            as is_scheduled_service,
    data_source,
    cast(departures_scheduled as double)           as departures_scheduled,
    cast(departures_performed as double)           as departures_performed,
    cast(payload as double)                        as payload_lbs,
    cast(seats as double)                          as seats,
    cast(passengers as double)                     as passengers,
    cast(freight as double)                        as freight_lbs,
    cast(mail as double)                           as mail_lbs,
    cast(distance as double)                       as distance_miles,
    cast(ramp_to_ramp as double)                   as ramp_to_ramp_minutes,
    cast(air_time as double)                       as air_minutes,
    origin_country = 'US' and dest_country = 'US'  as is_domestic
from {{ source('raw', 't100_segment') }}
